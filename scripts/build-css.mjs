#!/usr/bin/env node
// Builds css/tokens.<product>.css from tokens/*.json. No dependencies.
//
//   node scripts/build-css.mjs          write the files
//   node scripts/build-css.mjs --check  fail when a committed file is out of date
//
// One file for each product that renders with web technology. The products are
// equal: each file is the shared tokens plus that product's own token file,
// when it has one. No product is the base of another.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = (name) => JSON.parse(fs.readFileSync(path.join(ROOT, 'tokens', name), 'utf8'));

// product -> { font: key in typography.json fontStack, overlay: product token file or null }
export const PRODUCTS = Object.freeze({
  extension: { font: 'extension', overlay: null },
  website: { font: 'web', overlay: null },
  windows: { font: 'windows', overlay: 'windows.json' },
});

const NAME = /^[A-Za-z0-9][A-Za-z0-9-]*$/;
const COLOR = /^(#[0-9A-Fa-f]{6}|rgba\(\d{1,3},\d{1,3},\d{1,3},(0|1|0?\.\d+)\))$/;
const kebab = (name) => name.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase();

function px(value, where) {
  if (!Number.isFinite(value) || value < 0) throw new Error(`${where} must be a number of pixels`);
  return value === 0 ? '0' : `${value}px`;
}

export function declarations(product) {
  const spec = PRODUCTS[product];
  if (!spec) throw new Error(`unknown product: ${product}`);
  const overlay = spec.overlay ? read(spec.overlay) : {};
  const typography = read('typography.json');
  const out = [];
  const add = (name, value) => {
    if (!NAME.test(name)) throw new Error(`token name is not usable in CSS: ${name}`);
    out.push([`--${name}`, String(value)]);
  };

  for (const [name, value] of Object.entries({ ...read('colors.json'), ...(overlay.colors || {}) })) {
    if (!COLOR.test(value)) throw new Error(`colour ${name} has an unsupported value`);
    add(`color-${name}`, value);
  }
  const spacing = { ...read('spacing.json'), ...(overlay.spacing || {}) };
  for (const name of Object.keys(spacing).sort((a, b) => spacing[a] - spacing[b])) add(`space-${name}`, px(spacing[name], `spacing ${name}`));
  for (const [name, value] of Object.entries({ ...read('radius.json'), ...(overlay.radius || {}) })) add(`radius-${name}`, px(value, `radius ${name}`));

  if (!typography.fontStack[spec.font]) throw new Error(`no font stack for ${product}`);
  add('font-sans', typography.fontStack[spec.font]);
  add('font-mono', typography.fontStack.mono);
  for (const [role, value] of Object.entries(typography.scale)) {
    add(`type-${role}-size`, px(value.size, `type ${role} size`));
    add(`type-${role}-line-height`, px(value.lineHeight, `type ${role} line height`));
    add(`type-${role}-weight`, value.weight);
  }
  for (const [name, value] of Object.entries(read('motion.json'))) {
    add(`motion-${name}-duration`, `${value.duration}ms`);
    add(`motion-${name}-easing`, value.easing);
  }
  // A shadow is one layer: no horizontal offset, a vertical offset, a blur and a colour.
  for (const [name, value] of Object.entries(overlay.shadow || {})) {
    if (!COLOR.test(value.color)) throw new Error(`shadow ${name} has an unsupported colour`);
    add(`shadow-${name}`, `0 ${px(value.y, `shadow ${name} y`)} ${px(value.blur, `shadow ${name} blur`)} ${value.color}`);
  }
  for (const [name, value] of Object.entries(overlay.window || {})) {
    if (Array.isArray(value)) {
      add(`window-${kebab(name)}-width`, px(value[0], `window ${name}`));
      add(`window-${kebab(name)}-height`, px(value[1], `window ${name}`));
    } else add(`window-${kebab(name)}`, px(value, `window ${name}`));
  }
  return out;
}

export function css(product) {
  const sources = ['colors', 'spacing', 'radius', 'typography', 'motion'].map((name) => `tokens/${name}.json`);
  if (PRODUCTS[product].overlay) sources.push(`tokens/${PRODUCTS[product].overlay}`);
  const lines = [
    '/* GENERATED by scripts/build-css.mjs. Do not edit: change the token files and run the script. */',
    `/* Product: ${product}. Sources: ${sources.join(', ')}. */`,
    ':root {',
    ...declarations(product).map(([name, value]) => `  ${name}: ${value};`),
    '}',
    '',
  ];
  return lines.join('\n');
}

function main() {
  const check = process.argv.includes('--check');
  const outDir = path.join(ROOT, 'css');
  let stale = 0;
  for (const product of Object.keys(PRODUCTS)) {
    const file = path.join(outDir, `tokens.${product}.css`);
    const wanted = css(product);
    if (check) {
      const actual = fs.existsSync(file) ? fs.readFileSync(file, 'utf8').replace(/\r\n/g, '\n') : null;
      if (actual !== wanted) { stale += 1; console.error(`OUT OF DATE: css/tokens.${product}.css`); }
    } else {
      fs.mkdirSync(outDir, { recursive: true });
      fs.writeFileSync(file, wanted);
      console.log(`wrote css/tokens.${product}.css`);
    }
  }
  if (check) {
    if (stale) { console.error('Run: node scripts/build-css.mjs'); process.exit(1); }
    console.log('css tokens are up to date');
  }
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
